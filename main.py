# Сколько вопросов отображать на одной странице
QUESTIONS_PER_PAGE = 50


# Формирование страницы с вопросами
def get_questions_page(page=1):
    start = (page - 1) * QUESTIONS_PER_PAGE
    end = start + QUESTIONS_PER_PAGE
    question_items = list(questions.items())[start:end]
    question_list = "\n".join([f"{key}. {value}" for key, value in question_items])
    return question_list, len(questions)


# Генерация клавиатуры для навигации
def get_navigation_keyboard(current_page, total_questions):
    total_pages = -(-total_questions // QUESTIONS_PER_PAGE)  # Округление вверх
    keyboard = InlineKeyboardMarkup()
    buttons = []

    # Кнопка "Назад"
    if current_page > 1:
        buttons.append(InlineKeyboardButton("⬅️ Назад", callback_data=f"page_{current_page - 1}"))

    # Кнопка "Вперед"
    if current_page < total_pages:
        buttons.append(InlineKeyboardButton("Вперед ➡️", callback_data=f"page_{current_page + 1}"))

    if buttons:
        keyboard.row(*buttons)

    return keyboard


@bot.message_handler(commands=["start"])
def start(message):
    keyboard = ReplyKeyboardMarkup(resize_keyboard=True)
    keyboard.add(KeyboardButton("📋 Посмотреть список вопросов"))
    keyboard.add(KeyboardButton("❓ Получить ответ на вопрос"))
    bot.send_message(
        message.chat.id,
        f"Здравствуйте, {message.from_user.first_name}!\nВыберите действие, нажав на кнопку ниже.",
        reply_markup=keyboard,
    )


@bot.message_handler(func=lambda message: message.text == "📋 Посмотреть список вопросов")
def view_questions_handler(message):
    page = 1
    question_list, total_questions = get_questions_page(page)
    keyboard = get_navigation_keyboard(page, total_questions)

    bot.send_message(
        message.chat.id,
        f"📋 Список вопросов (Страница {page}):\n\n{question_list}",
        reply_markup=keyboard,
    )


@bot.callback_query_handler(func=lambda call: call.data.startswith("page_"))
def show_questions(call):
    # Получаем номер страницы из callback_data
    page = int(call.data.split("_")[1])
    question_list, total_questions = get_questions_page(page)
    keyboard = get_navigation_keyboard(page, total_questions)

    bot.edit_message_text(
        chat_id=call.message.chat.id,
        message_id=call.message.message_id,
        text=f"📋 Список вопросов (Страница {page}):\n\n{question_list}",
        reply_markup=keyboard,
    )


@bot.message_handler(func=lambda message: message.text == "❓ Получить ответ на вопрос")
def ask_question_number(message):
    bot.send_message(message.chat.id, "Введите номер вопроса, чтобы получить ответ.")


@bot.message_handler(func=lambda message: message.text.isdigit())
def provide_answer(message):
    question_number = int(message.text)
    if question_number in answers:
        # Получаем вопрос по номеру
        question_text = questions.get(question_number, "Вопрос не найден.")
        answer_text = answers[question_number]
        bot.send_message(
            message.chat.id,
            f"Ответ на вопрос {question_number}:\n\n"
            f"Вопрос: {question_text}\n\nОтвет: {answer_text}",
        )
    else:
        bot.send_message(
            message.chat.id,
            "Вопрос с таким номером отсутствует. Пожалуйста, введите корректный номер вопроса.",
        )





